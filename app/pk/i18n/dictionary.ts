/**
 * Urdu/English message catalogue for the Pakistan build.
 *
 * A hand-rolled dictionary rather than a library: `next-intl` and friends want either
 * a `[locale]` route segment or middleware locale negotiation plus a `next.config.ts`
 * plugin, and this app's config already carries hand-written webpack externals. For a
 * few hundred static labels a typed object buys everything the library would.
 *
 * `ur` is typed as `Record<MessageKey, string>`, so a missing Urdu translation is a
 * **build error** rather than a blank space discovered during a demo.
 *
 * ── Translation status ────────────────────────────────────────────────────────────
 * These strings are a first pass and MUST be reviewed by a native speaker before the
 * demo. Parliamentary Urdu is a specific register — the terms for calling-attention
 * notice, privilege motion and question of privilege are terms of art, not literal
 * translations, and getting them wrong in front of MNAs is worse than shipping
 * English. Keys marked `@review` below are the ones where I have the least
 * confidence; prioritise those.
 */

